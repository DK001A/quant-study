/* 去掉 HTML 标签 & 反转义，用于生成模板题 */
function plain(s){
  return String(s||'').replace(/<br\s*\/?>/gi,' ').replace(/<[^>]+>/g,'')
    .replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&amp;/g,'&')
    .replace(/&nbsp;/g,' ').replace(/\s+/g,' ').trim();
}
